import React from 'react'
import { describe, expect, it } from 'vitest'
import { render, screen, within, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../App'

const setup = () => { window.history.replaceState({}, '', '/dashboard'); const user = userEvent.setup(); render(<App/>); return user }

describe('mail workflows', () => {
  it('filters combined accounts and clears hidden selections during search', async () => {
    const user = setup()
    expect(screen.getByText('57 messages')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: /Gmail rohith/ }))
    expect(screen.getByText('19 messages')).toBeTruthy()
    await user.click(screen.getByRole('checkbox', { name: 'Select all visible emails' }))
    expect(screen.getByText('19 selected')).toBeTruthy()
    await user.type(screen.getByRole('textbox', { name: 'Search your emails' }), 'Horizon')
    expect(screen.getByText('1 messages')).toBeTruthy()
    expect(screen.queryByText('19 selected')).toBeNull()
  })
  it('archives a selection and restores a message from archive', async () => {
    const user = setup()
    await user.type(screen.getByRole('textbox', { name: 'Search your emails' }), 'Horizon')
    await user.click(screen.getByRole('checkbox', { name: 'Select all visible emails' }))
    await user.click(screen.getByRole('button', { name: 'Archive selected' }))
    await user.click(screen.getByRole('button', { name: 'Archive', exact: true }))
    const main = within(screen.getByRole('main'))
    await user.click(main.getByRole('button', { name: /Maya Chen/ }))
    await user.click(screen.getByTitle('Move to inbox'))
    await user.click(screen.getByRole('button', { name: /^Inbox/ }))
    expect(screen.getByText('57 messages')).toBeTruthy()
  })
  it('saves a draft, edits it, removes its attachment, sends it, and persists it', async () => {
    const user = setup()
    await user.click(screen.getByRole('button', { name: 'Compose mail' }))
    let dialog = within(screen.getByRole('dialog'))
    await user.type(dialog.getByPlaceholderText('name@example.com'), 'maya@example.com')
    await user.type(dialog.getByPlaceholderText('Add a subject'), 'Workflow check')
    await user.type(dialog.getByRole('textbox', { name: 'Message' }), 'Ready for review.')
    const fileInput = screen.getByRole('dialog').querySelector('input[type=file]')
    await user.upload(fileInput, new File(['Notes'], 'notes.txt', { type: 'text/plain' }))
    await waitFor(() => expect(dialog.getByText('notes.txt')).toBeTruthy())
    await user.click(dialog.getByRole('button', { name: 'Save draft' }))
    await user.click(screen.getByRole('button', { name: /^Drafts/ }))
    await user.click(within(screen.getByRole('main')).getByRole('button', { name: /Rohith Naidu/ }))
    await user.click(screen.getByRole('button', { name: 'Edit draft' }))
    dialog = within(screen.getByRole('dialog'))
    expect(dialog.getByText('notes.txt')).toBeTruthy()
    await user.click(dialog.getByRole('button', { name: 'Remove attachment' }))
    await user.click(dialog.getByRole('button', { name: 'Send mail' }))
    await waitFor(() => {
      const sent = JSON.parse(localStorage.getItem('mail-emails-v1')).find(mail => mail.subject === 'Workflow check')
      expect(sent.folder).toBe('sent')
      expect(sent.attachment).toBeNull()
    })
  })
  it('updates theme state and persists the choice', async () => {
    const user = setup()
    const toggle = screen.getByRole('switch', { name: 'Toggle dark mode' })
    await user.click(toggle)
    expect(document.documentElement.dataset.theme).toBe('light')
    expect(toggle.getAttribute('aria-checked')).toBe('false')
    expect(JSON.parse(localStorage.getItem('mail-theme-v1'))).toBe('light')
    await user.click(toggle)
    expect(document.documentElement.dataset.theme).toBe('dark')
  })
  it('adds another provider account and selects its empty inbox', async () => {
    const user = setup()
    await user.click(screen.getByRole('button', { name: 'Add another account' }))
    const dialog = within(screen.getByRole('dialog'))
    await user.click(dialog.getByRole('button', { name: 'Yahoo' }))
    await user.type(dialog.getByRole('textbox', { name: 'Email address' }), 'rohith@yahoo.com')
    await user.click(dialog.getByRole('button', { name: 'Add account' }))
    await user.click(screen.getByRole('button', { name: /Yahoo rohith@yahoo.com/ }))
    expect(screen.getByText('Nothing here yet')).toBeTruthy()
  })
  it('opens /sign-in by default with prefilled credentials and signs in in light mode', async () => {
    window.history.replaceState({}, '', '/')
    const user = userEvent.setup()
    render(<App/>)
    const emailInput = screen.getByRole('textbox', { name: 'Email address' })
    expect(emailInput.value).toBe('rohith.naidu@gmail.com')
    const passwordInput = screen.getByPlaceholderText('At least 8 characters')
    expect(passwordInput.value).toBe('password123')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    await waitFor(() => expect(screen.getByText('57 messages')).toBeTruthy())
    expect(document.documentElement.dataset.theme).toBe('light')
  })
})
